    private void btnBuscarAlumnoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarAlumnoActionPerformed
        // TODO add your handling code here:
        String id = txtIdAlumno.getText().trim();

if (id.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Ingrese el ID del alumno."
    );

    return;
}

alumnoSeleccionado = null;

for (modelo.Alumno alumno : alumnos) {

    if (alumno.getId().equalsIgnoreCase(id)) {

        alumnoSeleccionado = alumno;

        break;
    }
}

if (alumnoSeleccionado != null) {

    lblIdAlumno.setText(
            alumnoSeleccionado.getId()
    );

    lblNombreAlumno.setText(
            alumnoSeleccionado.getNombre()
    );

    lblSemestre.setText(
            String.valueOf(alumnoSeleccionado.getSemestre())
    );

    lblPrograma.setText(
            alumnoSeleccionado.getPrograma()
    );
    
    btnConfirmar.setEnabled(true);
    
} else {

    limpiarDatosAlumno();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Alumno no encontrado."
    );
    
    btnConfirmar.setEnabled(false);
    
}
    }//GEN-LAST:event_btnBuscarAlumnoActionPerformed

    private void lstTalleresValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstTalleresValueChanged
        // TODO add your handling code here:
        if (!evt.getValueIsAdjusting()) {

        int indice = lstTalleres.getSelectedIndex();

        if (indice >= 0) {

            tallerSeleccionado = talleres.get(indice);

            lblNombreTaller.setText(
                    tallerSeleccionado.getNombre()
            );

            lblInstructor.setText(
                    tallerSeleccionado.getInstructor()
            );

            lblFecha.setText(
                    tallerSeleccionado.getFecha()
            );

            lblHorario.setText(
                    tallerSeleccionado.getHorario()
            );

            lblLugar.setText(
                    tallerSeleccionado.getLugar()
            );

            lblCupo.setText(
                    String.valueOf(tallerSeleccionado.getCupo())
            );
        }
    }


    }//GEN-LAST:event_lstTalleresValueChanged

    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        // TODO add your handling code here:
        if (tallerSeleccionado == null) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Seleccione un taller."
    );

    return;
}

if (alumnoSeleccionado == null) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Primero debe buscar un alumno."
    );

    return;
}

modelo.Inscripcion inscripcion =
        new modelo.Inscripcion(
                alumnoSeleccionado,
                tallerSeleccionado
        );

txtTicket.setText(
        inscripcion.generarTicket()
);

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Inscripción realizada correctamente."
);
    }//GEN-LAST:event_btnConfirmarActionPerformed

